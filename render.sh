#!/bin/sh
# Writes Formula/ldaplens.rb for one ldaplens release from its checksums file.
# Usage: render.sh <tag, e.g. v1.7.1> <ldaplens_checksums.txt>
set -eu
tag=$1 sums=$2
case $tag in v[0-9]*.[0-9]*.[0-9]*) ;; *) echo "render.sh: tag $tag is not vX.Y.Z" >&2; exit 1 ;; esac
version=${tag#v}
url="https://github.com/cicdteam/ldaplens/releases/download/$tag"
sum() {
  s=$(awk -v f="ldaplens_$1.tar.gz" '$2 == f { print $1 }' "$sums")
  case $s in [0-9a-f]*) [ ${#s} -eq 64 ] && { echo "$s"; return; } ;; esac
  echo "render.sh: no SHA-256 for ldaplens_$1.tar.gz in $sums" >&2
  exit 1
}
darwin_arm=$(sum Darwin_arm64)
darwin_intel=$(sum Darwin_x86_64)
linux_arm=$(sum Linux_aarch64)
linux_intel=$(sum Linux_x86_64)

mkdir -p Formula
cat >Formula/ldaplens.rb <<EOF
# Generated by render.sh from the release's checksums: do not edit by hand.
class Ldaplens < Formula
  desc "Web UI to browse, search and edit LDAP: OpenLDAP and Active Directory"
  homepage "https://github.com/cicdteam/ldaplens"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$url/ldaplens_Darwin_arm64.tar.gz"
      sha256 "$darwin_arm"
    end
    on_intel do
      url "$url/ldaplens_Darwin_x86_64.tar.gz"
      sha256 "$darwin_intel"
    end
  end

  on_linux do
    on_arm do
      url "$url/ldaplens_Linux_aarch64.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$url/ldaplens_Linux_x86_64.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "ldaplens"
  end

  test do
    assert_equal "ldaplens v#{version}", shell_output("#{bin}/ldaplens --version").strip
  end
end
EOF
